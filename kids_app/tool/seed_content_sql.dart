// Generates the engine content of supabase/seed.sql (§14 configs and §15, the Phase 10 game
// collection) from lib/demo/, so the seed and demo mode play the same content:
//   dart run tool/seed_content_sql.dart           # prints the block
//   dart run tool/seed_content_sql.dart --write   # replaces it in supabase/seed.sql
// ignore_for_file: avoid_print
