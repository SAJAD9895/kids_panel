const _begin =
    '-- >>> generated by kids_app/tool/seed_content_sql.dart --write (do not edit by hand)';
const _end = '-- <<< generated';

String _q(String s) => s.replaceAll("'", "''");

String block(String schemaJson) {
  final out = StringBuffer()..writeln(_begin);
  void config(String slug, Object? cfg) {
    out.writeln(
      "update games set config = '${_q(jsonEncode(cfg))}'::jsonb -- engine:$slug",
    );
    out.writeln(
      "where activity_id = (select id from activities where slug = '$slug');",
    );
  }

  for (final e in demoActivityContent.entries) {
    config(e.key, e.value);
  }
  out
    ..writeln()
    ..writeln('-- ${'-' * 75}')
    ..writeln(
      '-- 15. The game collection (Phase 10, docs/games/game-catalog.md): eight games on the',
    )
    ..writeln(
      '-- learning engine, each with Easy / Medium / Hard levels, in the "Game room" home row.',
    )
    ..writeln('-- ${'-' * 75}')
    ..writeln(
      "insert into game_templates (key, version, runtime, orientation, supported_platforms, config_schema, status)",
    )
    ..writeln(
      "values ('learning_engine', '1.0.0', 'flutter', 'landscape', array['ios','android','web'],",
    )
    ..writeln("        '${_q(schemaJson)}'::jsonb, 'active');")
    ..writeln(
      'insert into activities (slug, type, title, description, keywords, subject_id, thumbnail_asset_id,',
    )
    ..writeln(
      '                        age_min_months, age_max_months, difficulty, players, estimated_seconds,',
    )
    ..writeln(
      '                        plus_only, free_eligible, status, published_at)',
    )
    ..writeln('values');
  for (final (i, g) in demoGames.indexed) {
    final sep = i == demoGames.length - 1 ? ';' : ',';
    out.writeln(
      "  ('${g.slug}', 'game', '${_q(jsonEncode({'en': g.title}))}', '${_q(jsonEncode({'en': g.description}))}', '${_q(g.keywords)}',",
    );
    out.writeln(
      "   (select id from subjects where key = '${g.subject}'), (select id from media_assets where object_path = 'thumbs/placeholder/1/512.webp'),",
    );
    out.writeln(
      "   ${g.ageMin}, ${g.ageMax}, 2, 1, ${g.seconds}, false, true, 'published', now() - interval '1 day')$sep",
    );
  }
  out
    ..writeln('insert into games (activity_id, template_id, config)')
    ..writeln(
      "select a.id, (select id from game_templates where key = 'learning_engine' and version = '1.0.0'), '{}'",
    )
    ..writeln(
      'from activities a where a.slug in (${demoGames.map((g) => "'${g.slug}'").join(', ')});',
    )
    ..writeln(
      "insert into collections (slug, surface, kind, title, sort, status, category_id)",
    )
    ..writeln(
      "values ('game-room', 'home', 'row', '{\"en\":\"Game room\"}', 2, 'published', null);",
    )
    ..writeln(
      'insert into collection_items (collection_id, activity_id, position)',
    )
    ..writeln(
      "select (select id from collections where slug = 'game-room'), a.id, x.p",
    )
    ..writeln(
      'from (values ${[for (final (i, g) in demoGames.indexed) "('${g.slug}', $i)"].join(', ')}) as x(slug, p)',
    )
    ..writeln('join activities a on a.slug = x.slug;');
  for (final g in demoGames) {
    config(g.slug, demoGameContent[g.slug]);
  }
  media(out);
  badges(out);
  out.write(_end);
  return out.toString();
}

void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent.parent;
  final schema = jsonEncode(
    jsonDecode(
      File('${root.path}/supabase/schemas/game-config.schema.json')
          .readAsStringSync(),
    ),
  );
  final text = block(schema);
  if (!args.contains('--write')) {
    print(text);
    return;
  }
  final seed = File('${root.path}/supabase/seed.sql');
  final s = seed.readAsStringSync();
  final a = s.indexOf(_begin), b = s.indexOf(_end);
  if (a < 0 || b < a) {
    stderr.writeln('markers not found in supabase/seed.sql');
    exit(1);
  }
  seed.writeAsStringSync(
    s.substring(0, a) + text + s.substring(b + _end.length),
  );
  print('updated supabase/seed.sql');
}

String _l(String en) => _q(jsonEncode({'en': en}));

/// §16: the development media library (Phase 11). Real files, generated by
/// content/dev-media/make_dev_media.py; uploaded to Storage by scripts/upload-dev-media.sh.
void media(StringBuffer out) {
  out
    ..writeln()
    ..writeln('-- ${'-' * 75}')
    ..writeln(
      '-- 16. Media library (Phase 11, docs/multimedia/): original videos, songs and stories made by',
    )
    ..writeln(
      '-- content/dev-media/make_dev_media.py. Upload the files with scripts/upload-dev-media.sh.',
    )
    ..writeln('-- ${'-' * 75}')
    ..writeln('insert into categories (key, name, sort, status) values');
  final cats = demoMediaCategories.where((c) => c.isNew).toList();
  for (final (i, c) in cats.indexed) {
    out.writeln(
      "  ('${c.key}', '${_l(c.name)}', ${c.sort}, 'published')${i == cats.length - 1 ? '' : ','}",
    );
  }
  out
    ..writeln('on conflict (key) do nothing;')
    ..writeln(
      'insert into media_assets (bucket, object_path, kind, mime_type, bytes, sha256, width, height, duration_ms, locale, access, status) values',
    );
  for (final (i, f) in devMediaFiles.indexed) {
    String n(int? v) => v == null ? 'null' : '$v';
    out.writeln(
      "  ('${f.bucket}', '${f.path}', '${f.kind}', '${f.mime}', ${f.bytes}, '${f.sha256}', ${n(f.width)}, ${n(f.height)}, "
      "${n(f.durationMs)}, ${f.locale == null ? 'null' : "'${f.locale}'"}, '${f.bucket == 'public-assets' ? 'public' : 'gated'}', 'ready')"
      "${i == devMediaFiles.length - 1 ? ';' : ','}",
    );
  }
  final fresh = demoMediaItems.where((m) => m.isNew).toList();
  out
    ..writeln(
      'insert into activities (slug, type, title, description, keywords, subject_id, primary_category_id, thumbnail_asset_id,',
    )
    ..writeln(
      '                        age_min_months, age_max_months, difficulty, players, estimated_seconds,',
    )
    ..writeln(
      '                        plus_only, free_eligible, status, published_at) values',
    );
  for (final (i, m) in fresh.indexed) {
    out.writeln(
      "  ('${m.slug}', '${m.type}', '${_l(m.title)}', '${_l(m.description)}', '${_q(m.keywords)}', "
      "(select id from subjects where key = '${m.subject}'), (select id from categories where key = '${m.category}'), "
      "(select id from media_assets where object_path = '${m.thumbnail}'), ${m.ageMin}, ${m.ageMax}, 1, 1, ${m.seconds}, "
      "${m.plus}, true, 'published', now() - interval '2 days')${i == fresh.length - 1 ? ';' : ','}",
    );
  }
  out.writeln(
    '-- the media activities already in §6 / §13: real length, category, thumbnail',
  );
  for (final m in demoMediaItems.where((m) => !m.isNew)) {
    out.writeln(
      "update activities set description = '${_l(m.description)}', estimated_seconds = ${m.seconds}, "
      "subject_id = (select id from subjects where key = '${m.subject}'), "
      "primary_category_id = (select id from categories where key = '${m.category}'), "
      "thumbnail_asset_id = (select id from media_assets where object_path = '${m.thumbnail}') where slug = '${m.slug}';",
    );
  }
  out.writeln(
    'insert into activity_media (activity_id, role, locale, position, asset_id, text) values',
  );
  final rows = <String>[];
  for (final m in demoMediaItems) {
    final pages = devStoryText[m.slug];
    for (final (role, f) in m.files) {
      if (role == 'thumb') continue;
      final pos = f.position ?? 0;
      final text = role == 'page_image' && pages != null
          ? "'${_l(pages[pos])}'"
          : 'null';
      final locale = role == 'subtitle' || role == 'audio_main' ? 'en' : 'und';
      rows.add(
        "  ((select id from activities where slug = '${m.slug}'), '$role', '$locale', $pos, "
        "(select id from media_assets where object_path = '${f.path}'), $text)",
      );
    }
  }
  out
    ..writeln(rows.join(',\n'))
    ..writeln(';')
    ..writeln(
      'insert into collections (slug, surface, kind, title, sort, status, category_id) values',
    );
  for (final (i, r) in demoMediaRows.indexed) {
    out.writeln(
      "  ('${r.$1}', '${r.$2}', '${r.$3}', '${_l(r.$4)}', ${i + 1}, 'published', null)${i == demoMediaRows.length - 1 ? '' : ','}",
    );
  }
  out
    ..writeln(
      'on conflict (slug) do update set title = excluded.title, kind = excluded.kind, sort = excluded.sort;',
    )
    ..writeln(
      'delete from collection_items where collection_id in (select id from collections where slug in (${demoMediaRows.map((r) => "'${r.$1}'").join(', ')}));',
    )
    ..writeln(
      'insert into collection_items (collection_id, activity_id, position) values',
    );
  final items = [
    for (final r in demoMediaRows)
      for (final (p, slug) in r.$5.indexed)
        "  ((select id from collections where slug = '${r.$1}'), (select id from activities where slug = '$slug'), $p)",
  ];
  out
    ..writeln(items.join(',\n'))
    ..writeln(';');
}

/// §17: the badges (Phase 12), from lib/demo/demo_rewards.dart. Artwork is in §16's files.
void badges(StringBuffer out) {
  String rarity(BadgeInfo b) => switch (b.rule) {
    BadgeRule.firstGame ||
    BadgeRule.firstLesson ||
    BadgeRule.firstCourse => 'special',
    _ when b.target >= 10 => 'rare',
    BadgeRule.weeklyGoals when b.target >= 4 => 'rare',
    _ => 'common',
  };
  out
    ..writeln()
    ..writeln('-- ${'-' * 75}')
    ..writeln(
      '-- 17. Badges (Phase 12, docs/gamification/achievement-system.md). Unlock rules are evaluated by',
    )
    ..writeln(
      '-- private.apply_rewards; artwork from content/dev-media/make_dev_media.py (§16 registers it).',
    )
    ..writeln('-- ${'-' * 75}')
    ..writeln(
      'insert into rewards (type, key, title, description, how_to_earn, asset_id, rarity, unlock_rule, rule_params,',
    )
    ..writeln('                     bonus_stars, sort, status) values');
  for (final (i, b) in demoBadges.indexed) {
    out.writeln(
      "  ('badge', '${b.key}', '${_l(b.title)}', '${_l(b.description)}', '${_l(b.howToEarn)}', "
      "(select id from media_assets where object_path = '${b.art}'), '${rarity(b)}', '${b.rule!.key}', "
      "'${_q(jsonEncode(b.params))}', ${b.bonusStars}, ${b.sort}, 'active')${i == demoBadges.length - 1 ? '' : ','}",
    );
  }
  out.writeln(
    'on conflict (key) do update set title = excluded.title, description = excluded.description, '
    'how_to_earn = excluded.how_to_earn, asset_id = excluded.asset_id, rarity = excluded.rarity, '
    'unlock_rule = excluded.unlock_rule, rule_params = excluded.rule_params, bonus_stars = excluded.bonus_stars, '
    'sort = excluded.sort, status = excluded.status;',
  );
}
