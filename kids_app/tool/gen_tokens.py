#!/usr/bin/env python3
"""Generates lib/core/theme/tokens.g.dart from the design tokens (docs/design/tokens/).

The design tokens are the only place values live (docs/design/README.md). Widgets use these
constants, never raw hex or pixel values. Re-run after changing tokens.json:

    python3 tool/gen_tokens.py            # writes the file
    python3 tool/gen_tokens.py --check    # exits 1 if the file is out of date (CI)
"""
import json, re, sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
TOKENS = APP.parent / "docs" / "design" / "tokens"
OUT = APP / "lib" / "core" / "theme" / "tokens.g.dart"

flutter = json.loads((TOKENS / "flutter_tokens.json").read_text())
source = json.loads((TOKENS / "tokens.json").read_text())

def camel(name: str) -> str:
    parts = re.split(r"[-_]", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return ("x" + out) if out[:1].isdigit() else out

def shadow(css: str) -> str:
    items = []
    for part in re.split(r",\s*(?![^()]*\))", css):
        m = re.match(r"\s*(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+rgba\((\d+),(\d+),(\d+),([\d.]+)\)", part)
        if not m:
            raise SystemExit(f"can't parse shadow {part!r}")
        x, y, blur, r, g, b, a = m.groups()
        alpha = round(float(a) * 255)
        items.append(f"BoxShadow(color: Color(0x{alpha:02X}{int(r):02X}{int(g):02X}{int(b):02X}), "
                     f"offset: Offset({x}, {y}), blurRadius: {blur})")
    return "[" + ", ".join(items) + "]"

def curve(css: str) -> str:
    nums = re.findall(r"-?[\d.]+", css)
    return "Cubic(" + ", ".join(n if "." in n else n + ".0" for n in nums) + ")"

lines = [
    "// GENERATED by tool/gen_tokens.py from docs/design/tokens/. Do not edit by hand.",
    "// ignore_for_file: constant_identifier_names",
    "import 'package:flutter/animation.dart';",
    "import 'package:flutter/painting.dart';",
    "",
    "/// Colour roles (docs/design/tokens/tokens.json › color).",
    "abstract final class AppColors {",
]
for k, v in flutter["colors"].items():
    lines.append(f"  static const {camel(k)} = Color({v});")
lines += ["}", "", "/// Spacing scale, in logical pixels. Index = step (space[4] = 12).",
          "abstract final class Space {"]
for i, v in enumerate(flutter["space"]):
    lines.append(f"  static const double s{i} = {float(v)};")
lines += ["}", "", "abstract final class Radii {"]
for k, v in flutter["radius"].items():
    lines.append(f"  static const double {camel(k)} = {float(v)};")
lines += ["}", "", "abstract final class Sizes {"]
for k, v in flutter["size"].items():
    lines.append(f"  static const double {camel(k)} = {float(v)};")
lines += ["}", "", "/// Material 3 window classes (docs/design/README.md §4).", "abstract final class Breakpoints {"]
for k, v in flutter["breakpoints"].items():
    lines.append(f"  static const double {camel(k)} = {float(v)};")
lines += ["}", "", "abstract final class Motion {"]
for k, v in flutter["motionMs"].items():
    lines.append(f"  static const {camel(k)} = Duration(milliseconds: {v});")
for k, v in flutter["curves"].items():
    lines.append(f"  static const {camel(k)} = {curve(v)};")
lines += ["}", "", "abstract final class Shadows {"]
for k, v in source["shadow"].items():
    lines.append(f"  static const {camel(k)} = {shadow(v)};")
lines += ["}", "", "/// Font families (bundled in assets/fonts, open licences).", "abstract final class FontFamilies {"]
for k, v in flutter["fontFamilies"].items():
    lines.append(f"  static const {camel(k)} = '{v}';")
lines += ["}", "", "/// One type style from the scale: family key, size, line height, weight.",
          "class TypeSpec {",
          "  const TypeSpec(this.family, this.size, this.line, this.weight);",
          "  final String family;", "  final double size;", "  final double line;", "  final int weight;", "}", ""]
for zone in ("kids", "ui"):
    lines.append(f"abstract final class {zone.capitalize()}Type {{")
    for k, v in flutter["type"][zone].items():
        fam = flutter["fontFamilies"].get(v["font"], "Inter" if v["font"] == "mono" else v["font"])
        lines.append(f"  static const {camel(k)} = TypeSpec('{fam}', {float(v['size'])}, {float(v['line'])}, {v['weight']});")
    lines.append("}")
    lines.append("")

import subprocess, tempfile

def formatted(source: str) -> str:
    """The generated file is kept `dart format`ted, so formatting the repo never makes it stale."""
    with tempfile.NamedTemporaryFile("w", suffix=".dart", delete=False) as f:
        f.write(source)
    subprocess.run(["dart", "format", f.name], check=True, capture_output=True)
    out = Path(f.name).read_text()
    Path(f.name).unlink()
    return out

text = formatted("\n".join(lines) + "\n")
if "--check" in sys.argv:
    ok = OUT.exists() and OUT.read_text() == text
    print("tokens.g.dart is up to date" if ok else "tokens.g.dart is stale: run python3 tool/gen_tokens.py")
    sys.exit(0 if ok else 1)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(text)
print(f"wrote {OUT.relative_to(APP)}")
