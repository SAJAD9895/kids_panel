// Generates src/app/theme.css (Tailwind v4 @theme) from the design tokens
// (docs/design/tokens/tokens.css) and copies the engine's game-config schema.
// Two vocabularies: grown-up (ui-*) for parent pages, kids (kids-*) for the child zone.
// Components use these classes only (bg-kids-learn-fill, p-s5, text-kids-title…), never raw colours or px.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const css = readFileSync(join(root, "docs/design/tokens/tokens.css"), "utf8");
// only the first (default) value of each token: the reduced-motion block redefines some
const seen = new Set();
const vars = [...css.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2].trim()]).filter(([k]) => !seen.has(k) && seen.add(k));
const out = ["/* GENERATED by scripts/sync-tokens.mjs from docs/design/tokens/tokens.css. Do not edit. */", "@theme {"];
const emit = (k, v) => out.push(`  --${k}: ${v};`);
for (const [k, v] of vars) {
  if (k.startsWith("color-")) emit(k, v); // bg-ui-surface, bg-kids-learn-fill, text-kids-ink
  else if (k.startsWith("space-")) emit(`spacing-s${k.slice(6)}`, v); // p-s5, gap-s3
  else if (k.startsWith("radius-")) emit(k, v); // rounded-md
  else if (k.startsWith("shadow-")) emit(k, v); // shadow-card, shadow-kid-raised
  else if (k.startsWith("font-")) emit(k, v); // font-kids, font-reading, font-display
  else if (k.startsWith("motion-ease-")) emit(`ease-${k.slice(12)}`, v); // ease-bounce
  else if (k.startsWith("size-")) emit(`spacing-${k.slice(5)}`, v); // min-h-tap-kids, w-kids-card-w, size-kids-node
  else if (k.startsWith("type-")) {
    const m = k.match(/^type-((?:ui|kids)-[a-z0-9-]+?)-(size|line|weight|tracking)$/);
    if (!m) continue;
    const [, name, part] = m;
    if (part === "size") emit(`text-${name}`, v);
    if (part === "line") emit(`text-${name}--line-height`, v);
    if (part === "weight") emit(`text-${name}--font-weight`, v);
    if (part === "tracking") emit(`text-${name}--letter-spacing`, v);
  }
}
out.push("}");
// motion durations as plain variables (used through var() in the few animations we have)
out.push(":root {");
for (const [k, v] of vars) if (/^motion-(instant|fast|base|slow|celebrate)$/.test(k)) out.push(`  --${k}: ${v};`);
out.push("}");
writeFileSync(join(here, "../src/app/theme.css"), out.join("\n") + "\n");
mkdirSync(join(here, "../src/lib/engine"), { recursive: true });
writeFileSync(join(here, "../src/lib/engine/game-config.schema.json"), readFileSync(join(root, "supabase/schemas/game-config.schema.json"), "utf8"));
console.log(`theme.css: ${out.length - 5} tokens; game-config.schema.json copied`);
