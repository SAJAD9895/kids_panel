// Generates src/app/theme.css (Tailwind v4 @theme) from the design tokens
// (docs/design/tokens/tokens.css) and copies the engine's game-config schema
// (supabase/schemas/game-config.schema.json). Run: npm run sync (also before build and test).
// Components use these classes only (bg-ui-surface, p-s5, rounded-md…), never raw colours or px.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const css = readFileSync(join(root, "docs/design/tokens/tokens.css"), "utf8");
const vars = [...css.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2].trim()]);
const out = ["/* GENERATED by scripts/sync-tokens.mjs from docs/design/tokens/tokens.css. Do not edit. */", "@theme {"];
const emit = (k, v) => out.push(`  --${k}: ${v};`);
for (const [k, v] of vars) {
  if (k.startsWith("color-ui-") || k.startsWith("color-admin-")) emit(k, v); // bg-ui-surface, text-admin-on-sidebar
  else if (k.startsWith("space-")) emit(`spacing-s${k.slice(6)}`, v); // p-s5, gap-s3
  else if (k.startsWith("radius-")) emit(k, v); // rounded-md
  else if (k.startsWith("shadow-")) emit(k, v); // shadow-card
  else if (k === "font-sans" || k === "font-mono" || k === "font-display") emit(k, v);
  else if (k.startsWith("size-ui-") || k.startsWith("size-icon-") || k === "size-tap-ui")
    emit(`spacing-${k.slice(5)}`, v); // w-ui-sidebar-w, h-ui-topbar-h, max-w-ui-content-max, size-icon-md
  else if (k.startsWith("type-ui-")) {
    const m = k.match(/^type-(ui-[a-z0-9-]+?)-(size|line|weight|tracking)$/);
    if (!m) continue;
    const [, name, part] = m;
    if (part === "size") emit(`text-${name}`, v);
    if (part === "line") emit(`text-${name}--line-height`, v);
    if (part === "weight") emit(`text-${name}--font-weight`, v);
    if (part === "tracking") emit(`text-${name}--letter-spacing`, v);
  }
}
out.push("}");
writeFileSync(join(here, "../src/app/theme.css"), out.join("\n") + "\n");
mkdirSync(join(here, "../src/lib/game"), { recursive: true });
writeFileSync(
  join(here, "../src/lib/game/game-config.schema.json"),
  readFileSync(join(root, "supabase/schemas/game-config.schema.json"), "utf8"),
);
console.log(`theme.css: ${out.length - 3} tokens; game-config.schema.json copied`);
